using System;
using System.Collections.Generic;
using TMPro;
using UnityEngine;

namespace DroneTrainer.UI
{
    [Serializable]
    public class NamedSprite
    {
        public string name;
        public Sprite sprite;
    }

    /// <summary>Design-kit tokens (Design/components.html) as an asset. Lives in Resources/UITheme.</summary>
    [CreateAssetMenu(menuName = "Drone Trainer/UI Theme")]
    public class UITheme : ScriptableObject
    {
        [Header("Surfaces")]
        public Color bg0 = Hex("07090C");
        public Color bg1 = Hex("0D1014");
        public Color panel = Hex("161A20");
        public Color panel2 = Hex("1F242C");
        public Color line = Hex("2B313B");
        public Color glass = new Color(0.05f, 0.063f, 0.078f, 0.72f);
        [Header("Text")]
        public Color text = Hex("E9EDF1");
        public Color textDim = Hex("9AA4B1");
        public Color textMute = Hex("5F6976");
        [Header("Accent & status")]
        public Color accent = Hex("46E0D2");
        public Color ok = Hex("4ADE80");
        public Color warn = Hex("FFB020");
        public Color danger = Hex("FF4D5E");
        public Color info = Hex("6EA8FF");

        [Header("Sprites (generated by Tools ▸ Drone Trainer ▸ 3)")]
        public Sprite rounded;       // r=16, sliced
        public Sprite roundedLarge;  // r=28, sliced
        public Sprite pill;          // fully round ends, sliced
        public Sprite circle;
        public Sprite ring;          // thick ring for gauges
        public Sprite softGlow;
        public Sprite gradient;      // vertical hangar gradient
        public List<NamedSprite> icons = new List<NamedSprite>();

        [Header("2D art (Assets/_Project/Art/UI)")]
        public Sprite navTile;
        public Sprite navTileActive;
        public Sprite quickCard;
        public Sprite droneSilhouette;
        public Sprite healthBar;
        public Sprite badgeAlert;
        public Sprite heroDrone;
        public Sprite railButton;
        public Sprite arrowButton;
        public Sprite startButton;
        public Sprite bottomBar;
        public Sprite statusTag;

        [Header("Fonts")]
        public TMP_FontAsset font;

        static UITheme current;
        public static UITheme Current
        {
            get
            {
                if (!current) current = Resources.Load<UITheme>("UITheme");
                if (!current) current = CreateInstance<UITheme>();
                return current;
            }
        }

        Dictionary<string, Sprite> lookup;
        public Sprite Icon(string name)
        {
            if (string.IsNullOrEmpty(name)) return null;
            if (lookup == null || lookup.Count != icons.Count)
            {
                lookup = new Dictionary<string, Sprite>();
                foreach (var i in icons) if (i != null && i.sprite) lookup[i.name] = i.sprite;
            }
            return lookup.TryGetValue(name, out var s) ? s : null;
        }

        public static Color Hex(string hex) => ColorUtility.TryParseHtmlString("#" + hex, out var c) ? c : Color.magenta;
        public static Color A(Color c, float a) { c.a = a; return c; }
    }
}
